export function countryCodeToFlag(code: string): string {
  if (!/^[A-Z]{2}$/.test(code)) return '🌐';
  const offset = 127397;
  return String.fromCodePoint(code.charCodeAt(0) + offset, code.charCodeAt(1) + offset);
}

