const COUNTRY_BY_CODE = new Map(WORLD_COUNTRIES.map((c) => [c.code, c]));

export function isValidCountryCode(code: unknown): code is string {
  return typeof code === 'string' && COUNTRY_BY_CODE.has(code);
}

export function getCountryByCode(code?: string | null): CountryOption | null {
  if (!code) return null;
  return COUNTRY_BY_CODE.get(code.toUpperCase()) ?? null;
}

export function normalizeCountrySearch(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}
